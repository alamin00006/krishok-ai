export type ContentSection = keyof typeof content;

@Injectable()
export class ContentService {
  getAll() {
    return content;
  }

  getDetail(section: string, id: string) {
    if (!(section in content)) return undefined;
    return content[section as ContentSection].find((item) => item.id === id);
  }
}
